# -*- coding: utf-8 -*-
"""jyotish_structure_lab.py — П11: что такое Вимшоттари СТРУКТУРНО.

Мандат 2026-07-27: пользователь эмпирически замечает, что махадаши хорошо
ложатся на ретроспективу жизни. Прежде чем что-либо утверждать про смысл,
разбираем ОБЪЕКТ — как разбирали колесо, И Цзин, Каббалу и триграммы.

Что здесь устанавливается (каждое — счётом, не мнением):

  [A] 120-летнее колесо: девять долей, суммы, доли жизни.
  [B] Самоподобие: вложенные уровни воспроизводят те же пропорции —
      Вимшоттари есть МУЛЬТИПЛИКАТИВНОЕ разбиение отрезка жизни, то есть
      каскад полос, а не список дат. Проверяется точно.
  [C] Однопараметричность: вся временная разметка жизни определяется ОДНИМ
      числом — фазой Луны внутри её накшатры. 48 чисел натала + 1.
  [D] Основание счёта: лунный слой троичен (27 = 3³ накшатр, владыка =
      остаток mod 9), дверной слой двоичен (64 = 2⁶). Проверяем, что это
      разные арифметики, а не одна в маскировке: есть ли гомоморфизм,
      совпадают ли границы.
  [E] Бюджет голосов жизни: если владык перевести в наши голоса телесной
      картой, сколько лет из 120 достаётся каждому голосу — производная
      величина, которой в традиции нет.

run: python3 architecture/jyotish_structure_lab.py
"""
import itertools
from fractions import Fraction

LORDS = [("Ketu", 7), ("Venus", 20), ("Sun", 6), ("Moon", 10), ("Mars", 7),
         ("Rahu", 18), ("Jupiter", 16), ("Saturn", 19), ("Mercury", 17)]
TOTAL = sum(y for _, y in LORDS)

print("=" * 72)
print("[A] колесо 120 лет: девять долей")
assert TOTAL == 120, TOTAL
for name, y in LORDS:
    print(f"  {name:<8} {y:>3} лет   доля {Fraction(y, 120)}  "
          f"({100 * y / 120:.1f} % жизни)")
print(f"  сумма = {TOTAL} [Т]")

print()
print("[B] самоподобие: вложенный уровень — те же пропорции")
# антардаша владыки j внутри махадаши i длится y_i * y_j / 120
ok = True
for i, (ni, yi) in enumerate(LORDS):
    tot = sum(Fraction(yi * yj, 120) for _, yj in LORDS)
    ok &= (tot == yi)
print("  для каждой махадаши сумма её антардаш равна её длине:",
      "да [Т]" if ok else "НЕТ")
# третий уровень
lvl3 = sum(Fraction(7 * yj, 120) * Fraction(yk, 120)
           for _, yj in LORDS for _, yk in LORDS)
print(f"  третий уровень внутри Кету: {lvl3} = {float(lvl3):.0f} лет — "
      f"снова длина махадаши [Т]")
print("  ⟹ Вимшоттари = мультипликативное (самоподобное) разбиение отрезка:")
print("     доля p_i = y_i/120 применяется на КАЖДОМ уровне, как каскад полос.")
print("     Это тот же тип объекта, что каскад НЧ-фильтров холархии (P4a).")

print()
print("[C] однопараметричность разметки")
print("  порядок владык фиксирован; от человека зависит только СТАРТ —")
print("  накшатра Луны (1 из 27) и доля пройденного внутри неё.")
print("  Значит вся сетка дат жизни = одно вещественное число φ ∈ [0,27):")
print("  индекс накшатры даёт владыку, дробная часть — остаток первой махадаши.")
print("  Следствие для нас: слой ДЕШЁВ (одно число сверх 48 натальных) и")
print("  потому плохо переобучается — это довод в пользу проверяемости [Т].")

print()
print("[D] основание счёта: троичный лунный слой против двоичного дверного")
print(f"  накшатр 27 = 3³; владыка = индекс mod 9 (гомоморфизм Z/27 → Z/9)")
print(f"  дверей 64 = 2⁶ (кодовые слова чётного веса над семью голосами)")
g = 1
for a, b in [(27, 64)]:
    while b:
        a, b = b, a % b
    g = a
print(f"  НОД(27, 64) = {g} ⟹ решётки взаимно просты: границы накшатр и")
print("  границы дверей не совпадают нигде, кроме нуля [Т].")
# сколько границ совпадает на круге 360°
nak = [i * 360.0 / 27 for i in range(27)]
door = [i * 360.0 / 64 for i in range(64)]
hits = sum(1 for a in nak for b in door if abs(a - b) < 1e-9)
print(f"  проверка счётом: совпавших границ {hits} из 27×64 — только 0° [Т]")
print("  ⟹ лунный и дверной слои ТРАНСВЕРСАЛЬНЫ, как деканы и двери (§атлас).")
print("     Это не дублирование: они делят круг несоизмеримо.")

print()
print("[E] бюджет голосов жизни (перевод владык в наши голоса)")
# карта тел в голоса — та же, что в движке (kb/энкодер): Солнце и Земля —
# светила; узлы (Раху/Кету) — зеркальная пара без собственного голоса.
BODY_VOICE = {"Sun": "O", "Moon": "E", "Mars": "D", "Mercury": "A",
              "Jupiter": "U", "Venus": "S", "Saturn": "L"}
NODES = {"Rahu", "Ketu"}
budget = {}
node_years = 0
for name, y in LORDS:
    if name in NODES:
        node_years += y
        continue
    budget[BODY_VOICE[name]] = budget.get(BODY_VOICE[name], 0) + y
print("  годы из 120, приходящиеся на каждый голос:")
for v in "ASDLEOU":
    y = budget.get(v, 0)
    print(f"    {v}: {y:>3} лет ({100 * y / 120:>4.1f} %)")
print(f"    узлы (Раху+Кету, голоса нет): {node_years} лет "
      f"({100 * node_years / 120:.1f} %)")
print(f"  сумма проверкой: {sum(budget.values()) + node_years} = 120 [Т]")
print()
print("  ЧТО ЭТО ЗНАЧИТ: традиция раздаёт жизни ОЧЕНЬ неравные доли по")
print("  голосам — форма (Венера, 20 лет) и смысл (Сатурн, 19) получают")
print("  втрое больше опоры (Солнце, 6). А пятая часть жизни (25 лет)")
print("  достаётся узлам, которым в нашей семёрке голоса не соответствует")
print("  вовсе: это в точности та пара, что у нас всегда была зеркальной.")
print("  Отсюда честный вопрос для исследования, а не утверждение:")
print("  является ли «период узла» временем БЕЗ голоса-хозяина — то есть")
print("  временем смены рамки, а не громкости? (гипотеза Г11-1)")

print()
print("=" * 72)
