print("  громче здесь. Даша переопределяет ВРЕМЕННУЮ: какое тело — хозяин")
print("  сейчас. Обе входят одной и той же дверью — весами тел в энкодере.")
print("  Значит архитектура не растёт: один механизм (μ-веса) поглощает")
print("  астрокартографию и джьотиш разом. Это и есть кристаллизация:")
print("  Γ_here_now = encode(натал, веса = место × период).")
