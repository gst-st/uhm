# -*- coding: utf-8 -*-
"""holarchy_ladder_lab.py — вертикаль уровней воедино + оператор захвата.

Три вопроса программы RECON-TOTAL (П3a и П4a), пререгистрированные:

  H1. АРИФМЕТИКА ВЛОЖЕННОСТИ [Т-повтор]. Пороги вложенных холонов
      P_crit^(n) = P_crit·3^(n−1)/(n+1) достигают невозможного (>1) на
      n=4: 54/35 — потолок вложенности SAD_MAX=3 (HL02). Здесь только
      воспроизводим арифметику как каркас вертикали.

  H2. ОПЕРАТОР ЗАХВАТА (П3a). Формализация: пропаганда = внешний источник
      ранг-1 состояния W («одна мысль» — предельно ЧИСТОЕ состояние),
      кормящий население через открытые каналы. Ключевое тождество нашей
      архитектуры: R = 1/(7P) и порог рефлексии R ≥ 1/3 дают
          уязвим ⟺ R < 1/3 ⟺ P > 3/7 —
      ГРАНИЦА ЗАХВАТА СОВПАДАЕТ С ГРАНИЦЕЙ ЭГО-РАСТВОРЕНИЯ (верх окна
      сознания T-124). Гипотеза-кристалл: пропаганда работает, ВЫТАЛКИВАЯ
      состояние за верхний край окна (повторение = очищение к W, снижение
      энтропии) и УДЕРЖИВАЯ его там; внутренний плюрализм (P в окне) —
      иммунитет. Прогноз SIS-типа: доля захваченных имеет ПОРОГ
      R₀ = β·v/γ = 1 (β — давление, v — доля уязвимых, γ — восстановление);
      ниже порога захват не перколирует. Проверяем агентной симуляцией.

  H3. ЧАСТОТНОЕ ОКНО УРОВНЯ (П4a). Уровень холархии с временной константой
      τ слышит сигналы периодов около своей полосы; агрегация вверх — это
      скользящее среднее, т.е. НЧ-фильтр. Пропускание синусоид через
      цепочку уровней (τ, 30τ, 900τ) показывает: каждый уровень отрезает
      быстрое соседа снизу; сигнал периода T слышен уровню n лишь при
      T ≳ τ_n. Отсюда честный статус космических периодов: год слышен
      жизни [Т-тривиально], прецессия (25 772 г) — на границе поколенческих
      уровней [Г], галактический год (~225 млн лет) — вне всех полос
      организменной вертикали [И].

Запуск: python3 architecture/holarchy_ladder_lab.py
"""
import math
import random

P_CRIT = 2.0 / 7.0
P_HI = 3.0 / 7.0


def h1():
    print("=" * 78)
    print("H1. Арифметика вложенности (каркас вертикали)")
    print("=" * 78)
    for n in range(1, 5):
        p = P_CRIT * 3 ** (n - 1) / (n + 1)
        note = "" if p <= 1 else "  ← НЕВОЗМОЖНО (P>1): потолок вложенности"
        print("  уровень n=%d: P_crit^(n) = 2/7·3^%d/%d = %.3f%s"
              % (n, n - 1, n + 1, p, note))
    print("  вердикт H1 [Т]: SAD_MAX=3 — вертикаль сознательных холонов")
    print("  обрывается на трёх уровнях вложенности; выше — только связь,")
    print("  не субъект (HL02).")


def h2():
    print("\n" + "=" * 78)
    print("H2. Оператор захвата: порог перколяции (П3a)")
    print("=" * 78)
    print("  тождество [Т]: уязвим ⟺ R<1/3 ⟺ P>3/7 — граница захвата =")
    print("  граница эго-растворения (верх окна сознания). Захват и транс —")
    print("  одна дверь, открытая с двух сторон.")
    print("  ЭРРАТА первой версии: «защита стартовым распределением» была")
    print("  опровергнута собственными числами (порог не сдвинулся: давление")
    print("  само выталкивает всех за край). Настоящая защита архитектуры —")
    print("  ЖИВОЙ ФИЛЬТР: пока P в окне, R = 1/(7P) ≥ 1/3 гасит повторение;")
    print("  ниже — развёртка по силе этого фильтра (культуре рефлексии c_R).")
    rng = random.Random(7)
    K = 400
    steps = 240
    gamma_rec = 0.05      # восстановление: быт/разнообразие возвращают в окно

    def run(beta, c_r):
        """Агенты P_k; давление очищает состояние (P↑), R-фильтр гасит его,
        пока агент в окне; за краем фильтр молчит и захват вероятен.
        Возвращает стационарную долю захваченных."""
        pk = [rng.uniform(P_CRIT + 0.01, P_HI + 0.02) for _ in range(K)]
        captured = [False] * K
        seed_pressure = 0.02
        for _ in range(steps):
            x = sum(captured) / K
            for k in range(K):
                if captured[k]:
                    if rng.random() < gamma_rec:
                        captured[k] = False
                        pk[k] = rng.uniform(P_CRIT + 0.01, P_HI - 0.01)
                    continue
                press = beta * (seed_pressure + x)
                r_k = 1.0 / (7.0 * pk[k])
                shield = c_r * min(1.0, r_k / (1.0 / 3.0)) \
                    if pk[k] <= P_HI else 0.0
                eff = press * (1.0 - 0.85 * shield)
                pk[k] = min(0.98, pk[k] + eff * 0.25)
                if pk[k] > P_HI and rng.random() < eff:
                    captured[k] = True
        return sum(captured) / K

    betas = [0.05, 0.1, 0.2, 0.3, 0.5, 0.8]
    print("\n  стационарная доля захваченных, по силе R-фильтра:")
    for c_r, label in [(0.0, "фильтра нет (c_R=0)"),
                       (0.6, "фильтр вполсилы (c_R=0.6)"),
                       (1.0, "полный фильтр (c_R=1)")]:
        row = "  %-24s" % label
        thr = None
        for b in betas:
            f = run(b, c_r)
            row += " %.2f→%2.0f%%" % (b, 100 * f)
            if thr is None and f > 0.25:
                thr = b
        print(row + "   порог β≈%s" % ("%.2f" % thr if thr else ">0.8"))
    print("  вердикт H2 [С]: захват перколяционен (порог по давлению есть), и")
    print("  порог сдвигается вправо с силой R-фильтра — защита живая, а не")
    print("  стартовая: удержание себя В ОКНЕ и есть иммунитет. Связка")
    print("  R=1/(7P) — [Т]; модель SIS-типа — игрушка, направление [С].")


def h3():
    print("\n" + "=" * 78)
    print("H3. Частотные окна вертикали (П4a)")
    print("=" * 78)
    # уровень = скользящее среднее с окном tau; пропускание синусоиды
    def transmission(period, tau):
        # среднее синуса по окну tau: |sinc|-подобное пропускание
        x = math.pi * tau / period
        return abs(math.sin(x) / x) if x > 1e-9 else 1.0

    taus = [1.0, 30.0, 900.0]   # уровень 1, 2, 3 (условные единицы)
    periods = [0.3, 1, 3, 10, 30, 100, 300, 1000, 3000]
    print("  пропускание сигнала периода T уровнем с окном τ (|sinc|):")
    print("  T\\τ      1      30     900")
    for T in periods:
        row = "  %-6g" % T
        for tau in taus:
            row += " %5.2f " % transmission(T, tau)
        print(row)
    print("  чтение: уровень слышит T ≳ τ (пропускание →1) и глух к T ≪ τ.")
    print("  вердикт H3 [С-модель]: вертикаль — каскад НЧ-фильтров; каждый")
    print("  уровень живёт в своей полосе и передаёт вверх только огибающую.")
    print("  следствие для космических периодов: год — в полосе организма;")
    print("  прецессия 25 772 г — полоса культурных/поколенческих холонов")
    print("  [Г]; галактический год ~2.3·10⁸ лет — вне полос всей живой")
    print("  вертикали: если он и «слышен», то не организмам [И].")


if __name__ == "__main__":
    h1()
    h2()
    h3()
