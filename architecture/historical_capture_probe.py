# -*- coding: utf-8 -*-
"""historical_capture_probe.py — P3b-пилот: кризис → захват, на датах XX века.

Модель П3 (holarchy_ladder_lab) говорит: массовый захват требует поля с
поднятой восприимчивостью — страх (S/O) вверх, принадлежность (U) разрушена,
рефлексия массово ниже порога. Исторический коррелят восприимчивости —
экономический шок. Пререгистрация P3b (ДО прогона):

  ГИПОТЕЗА: датированные установления авторитарных режимов лежат БЛИЖЕ к
  предшествующему глобальному экономическому шоку, чем случайные годы.
  СТАТИСТИКА: для каждого захвата lag = (год захвата − год ближайшего
  предшествующего шока); сравниваем средний lag с нуль-ансамблем 20 000
  равномерных размещений тех же N событий по 1900–2020.
  ЧЕСТНОСТЬ: N мал (пилот [И/С]); список событий — консенсусные даты
  учебников, выбранные ДО подсчёта; плотность шоков высока, поэтому нуль
  сам по себе даёт малые лаги — значим только ОТРЫВ от нуля. Датировки
  захватов НЕ подгонялись: список зафиксирован в коде до первого запуска.

P3c (селекция vs трансляция) требует рядов связности медиа — здесь только
формулировка долга: остаточная синхронность авторитарных волн СВЕРХ
объяснимой связностью экономики/медиа отличила бы трансляцию от селекции.

Запуск: python3 architecture/historical_capture_probe.py
"""
import random

# консенсусные «установления/переломы» авторитарных режимов (год):
CAPTURES = [
    ("Италия, поход на Рим", 1922),
    ("СССР, сталинский перелом", 1929),
    ("Германия, канцлерство НСДАП", 1933),
    ("Испания, конец гражданской", 1939),
    ("Аргентина, переворот GOU", 1943),
    ("Китай, установление КНР", 1949),
    ("Куба, революция", 1959),
    ("Греция, чёрные полковники", 1967),
    ("Чили, переворот", 1973),
    ("Аргентина, Процесс", 1976),
    ("Пакистан, Зия-уль-Хак", 1977),
    ("Иран, исламская революция", 1979),
    ("Турция, переворот Эврена", 1980),
    ("Египет, июльский переворот", 2013),
    ("Таиланд, переворот NCPO", 2014),
]

# глобальные/мировые экономические шоки (год начала):
SHOCKS = [1907, 1914, 1920, 1929, 1937, 1947, 1957, 1973, 1979, 1990,
          1997, 2000, 2008, 2020]


def mean_lag(years, shocks):
    lags = []
    for y in years:
        prior = [s for s in shocks if s <= y]
        if prior:
            lags.append(y - max(prior))
    return sum(lags) / len(lags), lags


def main():
    print("=" * 78)
    print("P3b-пилот: лаг «шок → установление автократии» против случая")
    print("=" * 78)
    years = [y for _, y in CAPTURES]
    obs, lags = mean_lag(years, SHOCKS)
    print("\n  события (%d):" % len(years))
    for (name, y), lag in zip(CAPTURES, lags):
        print("    %-34s %d  — %d г. после шока %d"
              % (name, y, lag, y - lag))
    print("\n  средний лаг: %.2f года" % obs)

    rng = random.Random(7)
    null = []
    for _ in range(20000):
        ys = [rng.randint(1900, 2020) for _ in years]
        m, _ = mean_lag(ys, SHOCKS)
        null.append(m)
    nm = sum(null) / len(null)
    nsd = (sum((x - nm) ** 2 for x in null) / len(null)) ** 0.5
    z = (obs - nm) / max(1e-9, nsd)
    p = sum(1 for x in null if x <= obs) / len(null)
    print("  нуль (20 000 равномерных размещений): %.2f ± %.2f" % (nm, nsd))
    print("  z = %+.2f · односторонний p (лаг ≤ наблюдённого) = %.3f"
          % (z, p))
    verdict = ("захваты ЖМУТСЯ к шокам — восприимчивость поля видна в датах"
               if p < 0.05 else
               "отрыва от случая НЕ видно — на этом наборе дат гипотеза "
               "упреждения не подтверждается")
    print("  вердикт P3b [И/С-пилот]: %s." % verdict)
    print("\n  долг P3c: ряды связности медиа/экономики для различения")
    print("  «селекция vs трансляция» (остаточная синхронность сверх")
    print("  связности) — без них вопрос первоисточника остаётся открытым.")


if __name__ == "__main__":
    main()
