SHOCKS_WIN = [s for s in SHOCKS if 1946 <= s <= 2010]


def v2():
    print("\n" + "=" * 78)
    print("P3b-v2: полный реестр GWF (N=%d) против случая" % len(GWF_STARTS))
    print("=" * 78)
    obs, lags = mean_lag(GWF_STARTS, SHOCKS_WIN)
    frac2 = sum(1 for x in lags if x <= 2) / len(lags)
    print("  шоки в окне: %s" % SHOCKS_WIN)
    print("  средний лаг: %.2f года · доля лагов ≤2: %.0f%%"
          % (obs, 100 * frac2))
    rng = random.Random(11)
    null_m, null_f = [], []
    for _ in range(20000):
        ys = [rng.randint(1946, 2010) for _ in GWF_STARTS]
        m, ls = mean_lag(ys, SHOCKS_WIN)
        null_m.append(m)
        null_f.append(sum(1 for x in ls if x <= 2) / len(ls))
    nm = sum(null_m) / len(null_m)
    nsd = (sum((x - nm) ** 2 for x in null_m) / len(null_m)) ** 0.5
    z = (obs - nm) / max(1e-9, nsd)
    pv = sum(1 for x in null_m if x <= obs) / len(null_m)
    fm = sum(null_f) / len(null_f)
    fsd = (sum((x - fm) ** 2 for x in null_f) / len(null_f)) ** 0.5
    zf = (frac2 - fm) / max(1e-9, fsd)
    pf = sum(1 for x in null_f if x >= frac2) / len(null_f)
    print("  нуль: лаг %.2f ± %.2f → z=%+.2f, p=%.4f" % (nm, nsd, z, pv))
    print("  нуль: доля≤2 %.0f%% ± %.1f%% → z=%+.2f, p=%.4f"
          % (100 * fm, 100 * fsd, zf, pf))
    verdict = ("старты автократий ЖМУТСЯ к шокам — восприимчивость поля "
               "видна на полном реестре"
               if pv < 0.01 else
               ("слабый сигнал (p<0.05, не <0.01) — направление есть, "
                "порог строгий не взят" if pv < 0.05 else
                "отрыва от случая НЕТ на полном реестре — гипотеза "
                "упреждения шоками в среднем по всем автократиям не живёт"))
    print("  вердикт P3b-v2 [С]: %s." % verdict)
    print("  чтение при нуле: пилотные 15 были ГРОМКИМИ случаями (великие")
    print("  державы, учебники); полный реестр полон малых переворотов с")
    print("  локальными причинами — глобальный шок не единственный вход в")
    print("  восприимчивость; следующий срез — локальные кризисы страны-года.")


if __name__ == "__main__":
    main()
    v2()
