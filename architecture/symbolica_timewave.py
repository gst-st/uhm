"""symbolica_timewave.py — Time Wave Zero Маккены против нашего колеса, СТРУКТУРНО.

Маккена строил «волну новизны» из последовательности Кинг Вэнь: первые
разности (сколько черт меняется между соседними гексаграммами) дают 64
числа, разворачиваемые на решётке 384 = 64×6. Мы не проверяем эсхатологию
(нулевая дата 2012 опровергнута календарём); мы спрашиваем, ЧТО в самой
конструкции — структура, а что — конвенция. Пререристрированные вопросы:

  TW1. РЕШЁТКА. 384 Маккены (64 гексаграммы × 6 черт; он же связывал это с
       лунным годом 13×29.53 ≈ 384) — та же мощность, что 384 линейных
       делений нашего колеса (64 двери × 6 линий), по которым Солнце
       проходит ровно за год, а Луна — за сидерический месяц. Совпадение
       мощности — [Т] тривиально; вопрос: несёт ли РАЗМЕТКА Кинг Вэнь
       что-то, чего нет у случайного порядка?
  TW2. ПРОФИЛЬ РАЗНОСТЕЙ. h(i) = popcount(KW[i] XOR KW[i+1]) — «шаг
       новизны». Средний шаг, дисперсия, автокорреляция — против нулевого
       ансамбля случайных перестановок 64 гексаграмм. Известная структура:
       Кинг Вэнь идёт ПАРАМИ (переворот, при симметрии — инверсия); честный
       вопрос — выделяется ли последовательность и ЗА пределами пар.
  TW3. КОЛЕСО ПРОТИВ КНИГИ. Тот же профиль для порядка колеса (наш WHEEL,
       он же порядок Рейва): у солнечного года своя «волна новизны» —
       h-профиль дверей, которые Солнце открывает подряд. Гипотеза
       Маккены-по-духу: у осмысленного порядка шаг новизны структурнее
       случайного. Сравниваем ОБА порядка с нулём — и друг с другом.

Запуск: python3 architecture/symbolica_timewave.py
"""
import random
from statistics import mean, pstdev

# King Wen line codes (bit k = line k+1, снизу вверх) — сверено с движком
# (core/src/recon.rs KW_BITS) и с genetics_lab.py.
KW_BITS = [
    0b111111, 0b000000, 0b010001, 0b100010, 0b010111, 0b111010, 0b000010,
    0b010000, 0b110111, 0b111011, 0b000111, 0b111000, 0b111101, 0b101111,
    0b000100, 0b001000, 0b011001, 0b100110, 0b000011, 0b110000, 0b101001,
    0b100101, 0b100000, 0b000001, 0b111001, 0b100111, 0b100001, 0b011110,
    0b010010, 0b101101, 0b011100, 0b001110, 0b111100, 0b001111, 0b101000,
    0b000101, 0b110101, 0b101011, 0b010100, 0b001010, 0b100011, 0b110001,
    0b011111, 0b111110, 0b011000, 0b000110, 0b011010, 0b010110, 0b011101,
    0b101110, 0b001001, 0b100100, 0b110100, 0b001011, 0b001101, 0b101100,
    0b110110, 0b011011, 0b110010, 0b010011, 0b110011, 0b001100, 0b010101,
    0b101010,
]

# Порядок колеса (движок core/src/wheel.rs WHEEL): двери, которые Солнце
# открывает подряд за год, начиная с 302° эклиптики.
WHEEL = [
    41, 19, 13, 49, 30, 55, 37, 63, 22, 36, 25, 17, 21, 51, 42, 3,
    27, 24, 2, 23, 8, 20, 16, 35, 45, 12, 15, 52, 39, 53, 62, 56,
    31, 33, 7, 4, 29, 59, 40, 64, 47, 6, 46, 18, 48, 57, 32, 50,
    28, 44, 1, 43, 14, 34, 9, 5, 26, 11, 10, 58, 38, 54, 61, 60,
]


def popcount(x):
    return bin(x).count("1")


def profile(order):
    """Циклический профиль шагов новизны h(i) для порядка гексаграмм."""
    n = len(order)
    return [popcount(KW_BITS[order[i] - 1] ^ KW_BITS[order[(i + 1) % n] - 1])
            for i in range(n)]


def stats(hs):
    m = mean(hs)
    s = pstdev(hs)
    # автокорреляция лаг-1 (структура «пары»: чередование малых/больших шагов)
    n = len(hs)
    ac = (sum((hs[i] - m) * (hs[(i + 1) % n] - m) for i in range(n))
          / max(1e-12, n * s * s)) if s > 0 else 0.0
    return m, s, ac


# Порядок Мавандуй (рукопись ~168 до н.э.): гексаграммы идут БЛОКАМИ по
# верхней триграмме (8 групп по 8), внутри блока меняется нижняя. Канонический
# ключ блоков: Цянь(111) Гэнь(100) Кань(010) Чжэнь(001) Кунь(000) Дуй(110)
# Ли(101) Сюнь(011); нижние — в том же ключе, начиная с одноимённой.
# Здесь биты триграммы = (нижняя черта, средняя, верхняя) снизу вверх.
MWD_KEY = [0b111, 0b001, 0b010, 0b100, 0b000, 0b110, 0b101, 0b011]
# ВНИМАНИЕ к кодировке: гексаграмма = нижняя триграмма (биты 0-2) + верхняя
# (биты 3-5); черта 1 — нижняя. Гэнь = гора = одна ян НАВЕРХУ триграммы =
# 0b100 (черта 3), Чжэнь = гром = ян внизу = 0b001. В ключе выше их места
# заданы по каноническому списку семей (отец, младший сын, средний, старший,
# мать, младшая дочь, средняя, старшая) — сверено по структуре рукописи.


def mawangdui_order():
    order = []
    for gi, up in enumerate(MWD_KEY):
        lows = MWD_KEY[gi:] + MWD_KEY[:gi]
        for low in lows:
            bits = low | (up << 3)
            order.append(KW_BITS.index(bits) + 1)
    return order


def main():
    print("=" * 78)
    print("symbolica_timewave — волна новизны: Кинг Вэнь, колесо, случай")
    print("=" * 78)

    print("\nTW1. Решётка 384")
    print("  Маккена: 64 гексаграммы × 6 черт = 384; лунный год 13×29.53 ≈ 384 дн.")
    print("  Наше колесо: 64 двери × 6 линий = 384 деления; Солнце проходит их")
    print("  за год (≈0.95 сут/линия), Луна — за сидерический месяц.")
    print("  Вердикт TW1: общая решётка 384 = общая КОМБИНАТОРИКА 2^6 × 6, а не")
    print("  общая динамика; сходство мощности [Т], всё сверх того требует TW2-3.")

    kw_order = list(range(1, 65))
    hs_kw = profile(kw_order)
    hs_wh = profile(WHEEL)
    m_kw, s_kw, ac_kw = stats(hs_kw)
    m_wh, s_wh, ac_wh = stats(hs_wh)

    # нулевой ансамбль: случайные перестановки 64 гексаграмм
    rng = random.Random(7)
    null_m, null_s, null_ac = [], [], []
    for _ in range(20000):
        p = kw_order[:]
        rng.shuffle(p)
        m, s, ac = stats(profile(p))
        null_m.append(m)
        null_s.append(s)
        null_ac.append(ac)
    nm, nsd = mean(null_m), pstdev(null_m)
    sm, ssd = mean(null_s), pstdev(null_s)
    am, asd = mean(null_ac), pstdev(null_ac)

    def z(x, mu, sd):
        return (x - mu) / max(1e-12, sd)

    print("\nTW2. Профиль разностей Кинг Вэнь против случая (20 000 перестановок)")
    print("  шаги h: KW %s..." % hs_kw[:12])
    print("  средний шаг: KW %.3f · случай %.3f±%.3f → z=%+.1f"
          % (m_kw, nm, nsd, z(m_kw, nm, nsd)))
    print("  разброс шага: KW %.3f · случай %.3f±%.3f → z=%+.1f"
          % (s_kw, sm, ssd, z(s_kw, sm, ssd)))
    print("  автокорр. лаг-1: KW %+.3f · случай %+.3f±%.3f → z=%+.1f"
          % (ac_kw, am, asd, z(ac_kw, am, asd)))
    within = [popcount(KW_BITS[2 * k] ^ KW_BITS[2 * k + 1]) for k in range(32)]
    across = [popcount(KW_BITS[2 * k + 1] ^ KW_BITS[(2 * k + 2) % 64])
              for k in range(32)]
    print("  внутри пар: средний шаг %.2f · между парами %.2f"
          % (mean(within), mean(across)))
    print("  вердикт TW2: если |z| велики — Кинг Вэнь как ПОРЯДОК несёт")
    print("  структуру (пары переворота/инверсии — известный механизм);")
    print("  вклад ЗА парами виден по автокорреляции и разбросу.")

    mwd = mawangdui_order()
    hs_m = profile(mwd)
    m_m, s_m, ac_m = stats(hs_m)
    print("\nTW2b. Мавандуй (блочный порядок рукописи) против случая")
    print("  средний шаг: MWD %.3f → z=%+.1f" % (m_m, z(m_m, nm, nsd)))
    print("  разброс:     MWD %.3f → z=%+.1f" % (s_m, z(s_m, sm, ssd)))
    print("  автокорр.:   MWD %+.3f → z=%+.1f" % (ac_m, z(ac_m, am, asd)))
    from collections import Counter as _C
    print("  спектр шагов MWD: %s" % dict(sorted(_C(hs_m).items())))
    within_blk = [h for i, h in enumerate(hs_m) if i % 8 != 7]
    across_blk = [h for i, h in enumerate(hs_m) if i % 8 == 7]
    print("  внутри блоков: средний %.2f · на стыках блоков: %.2f"
          % (mean(within_blk), mean(across_blk)))
    print("  вердикт TW2b: каталожный ход — внутри блока меняется только")
    print("  нижняя триграмма (шаги ≤3), стыки — скачки; третий характер:")
    print("  не рассказ и не календарь, а СЛОВАРЬ (сортировка по старшинству")
    print("  семей). Три канонических порядка = три модальности времени. [Т]")

    print("\nTW3. Колесо (порядок Рейва / наш годовой ход) против случая")
    print("  средний шаг: WHEEL %.3f → z=%+.1f" % (m_wh, z(m_wh, nm, nsd)))
    print("  разброс:     WHEEL %.3f → z=%+.1f" % (s_wh, z(s_wh, sm, ssd)))
    print("  автокорр.:   WHEEL %+.3f → z=%+.1f" % (ac_wh, z(ac_wh, am, asd)))
    from collections import Counter
    cw = Counter(hs_wh)
    ck = Counter(hs_kw)
    print("  спектр шагов WHEEL: %s — и НИ ОДНОЙ полной инверсии (6)"
          % dict(sorted(cw.items())))
    print("  спектр шагов KW:    %s — и ни одного шага 5"
          % dict(sorted(ck.items())))
    print("  почти-удвоение колеса: 34·16·8·4·2 (точное 32·16·8·4·2 даёт 62;")
    print("  колесо добирает два лишних 1-битных шага) — грей-ходность как")
    print("  ЗАКОН УБЫВАНИЯ: доля шага h падает примерно вдвое с каждым битом.")
    print("  вердикт TW3: колесо на порядок дальше от случая, чем книга, и в")
    print("  противоположную сторону: книга УКРУПНЯЕТ шаги (пары-скачки),")
    print("  колесо их МИНИМИЗИРУЕТ (плавная развёртка года).")

    print("\n" + "=" * 78)
    print("Итог (честно): «волна новизны» — функционал ПОРЯДКА на 64 узлах.")
    print("Проверяемое ядро TWZ — не дата конца, а утверждение «канонический")
    print("порядок статистически особен»; выше — его прямая проверка на двух")
    print("канонических порядках против нуля. Статусы: TW1 [Т] (мощность),")
    print("TW2-3 [С] (эмпирика на фикс. ансамбле), интерпретация novelty [И].")


if __name__ == "__main__":
    main()
