#!/usr/bin/env python3
"""Build complete, source-faithful Markdown editions for external reading.

Requires Python 3 and Bun (only to read the repository's TypeScript sidebar).
Run from any directory: python3 scripts/build-markdown.py [--output-dir PATH].
Source bodies, including equations, code, status markers and original links,
are preserved byte-for-byte. Source paths in the contents resolve those original
links without requiring a website checkout. No internal/research scratch files
or application code are included in the documentation corpus.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "website" if (ROOT / "website/docs").is_dir() else ROOT
DOCS = SITE / "docs"
SIDEBAR = SITE / "sidebars.ts"
TITLE = "UHM / УГМ" if SITE != ROOT else "Diakrisis"
BASENAME = "uhm" if SITE != ROOT else "diakrisis"


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def fenced(data: str, language: str) -> str:
    runs = [len(x) for x in re.findall(r"`+", data)]
    fence = "`" * max(3, max(runs, default=0) + 1)
    return f"{fence}{language}\n{data}" + ("" if data.endswith("\n") else "\n") + f"{fence}\n"


def files(root: Path) -> dict[str, Path]:
    result = {}
    for path in sorted(root.rglob("*")):
        if path.is_file() and path.suffix in {".md", ".mdx"}:
            key = path.relative_to(root).with_suffix("").as_posix()
            if key in result:
                raise ValueError(f"Duplicate documentation ID: {key}")
            result[key] = path
    return result


def metadata(data: bytes) -> tuple[str, bytes]:
    match = re.match(rb"\A---\r?\n(.*?)\r?\n---(?:\r?\n|$)", data, re.S)
    return (match[1].decode("utf-8"), data[match.end():]) if match else ("", data)


def title(meta: str, body: bytes, fallback: str) -> str:
    found = re.search(r"^title:\s*(.+)$", meta, re.M)
    if found:
        return found[1].strip().strip("\"'")
    found = re.search(r"^#\s+(.+)$", body.decode("utf-8"), re.M)
    return found[1].strip() if found else fallback


def sidebar_order(available: dict[str, Path]) -> list[str]:
    if not shutil.which("bun"):
        raise RuntimeError("Bun is required to read sidebars.ts; install Bun and rerun.")
    command = ["bun", "-e", "const m = await import(" + json.dumps(str(SIDEBAR)) +
               "); console.log(JSON.stringify(m.default));"]
    config = json.loads(subprocess.check_output(command, cwd=SITE, text=True))
    result = []

    def visit(item):
        if isinstance(item, str):
            result.append(item)
        elif isinstance(item, list):
            for child in item:
                visit(child)
        elif isinstance(item, dict):
            kind = item.get("type")
            if kind == "doc":
                result.append(item["id"])
            elif kind == "category":
                if item.get("link", {}).get("type") == "doc":
                    result.append(item["link"]["id"])
                visit(item.get("items", []))
            elif kind == "autogenerated":
                prefix = item["dirName"].strip("./")
                result.extend(k for k in sorted(available) if not prefix or k.startswith(prefix + "/"))
            elif kind == "link":
                return  # External navigation is not a documentation file.
            else:
                raise ValueError(f"Unsupported sidebar item: {item!r}")
        else:
            raise ValueError(f"Unsupported sidebar value: {item!r}")

    for items in config.values():
        visit(items)
    missing = sorted(set(result) - set(available))
    if missing:
        raise ValueError(f"Sidebar references missing documents: {missing}")
    # Several navigation paths may share a document; its content appears once.
    return list(dict.fromkeys(result))


def build(edition: str, entries: dict[str, Path], order: list[str], output: Path,
          fallback: list[str]) -> dict:
    unlisted = sorted(set(entries) - set(order))
    ordered = order + unlisted
    assert len(ordered) == len(set(ordered)) == len(entries)
    snapshots = {key: entries[key].read_bytes() for key in ordered}
    chunks = [f"# {TITLE} — complete corpus ({edition})\n\n",
              "This is a complete textual edition, not a summary. Documents follow the "
              "sidebar order; documents outside navigation follow in source-path order. "
              "Every original body is preserved byte-for-byte, including mathematics, "
              "code and epistemic status markers. YAML metadata is retained in fenced "
              "blocks. Original links identify documents through the source-path index "
              "below; external references and binary illustrations remain references.\n\n",
              "## Source-path index\n\n"]
    names = {}
    for number, key in enumerate(ordered, 1):
        meta, body = metadata(snapshots[key])
        names[key] = title(meta, body, key)
        chunks.append(f"- [{number}. {names[key]}](#{BASENAME}-{edition}-document-{number}): `{key}`\n")
    if fallback:
        chunks.append("\nTranslation unavailable; these documents use the original edition: " +
                      ", ".join(f"`{key}`" for key in fallback) + ".\n")
    records = []
    for number, key in enumerate(ordered, 1):
        data = snapshots[key]
        meta, body = metadata(data)
        path = entries[key].relative_to(ROOT).as_posix()
        chunks.append(f'\n\n---\n\n<a id="{BASENAME}-{edition}-document-{number}"></a>\n\n'
                      f"# {number}. {names[key]}\n\nSource: `{path}`\n\n")
        if meta:
            chunks.append(fenced(meta, "yaml") + "\n")
        marker = f"<!-- BEGIN SOURCE BODY {number}: {path} -->\n"
        ending = f"\n<!-- END SOURCE BODY {number} -->"
        if marker.encode() in data or ending.encode() in data:
            raise ValueError("Source collides with export delimiter: " + path)
        chunks.extend([marker, body.decode("utf-8"), ending, "\n"])
        records.append({"id": key, "path": path, "bytes": len(data), "sha256": sha(data),
                        "body_bytes": len(body), "body_sha256": sha(body), "ordinal": number})
    assembled = "".join(chunks).encode("utf-8")
    # Verify actual published bodies, not just an input count.
    for record in records:
        n, path = record["ordinal"], record["path"]
        start = f"<!-- BEGIN SOURCE BODY {n}: {path} -->\n".encode()
        stop = f"\n<!-- END SOURCE BODY {n} -->".encode()
        assert assembled.count(start) == assembled.count(stop) == 1
        extracted = assembled.split(start, 1)[1].split(stop, 1)[0]
        assert (len(extracted), sha(extracted)) == (record["body_bytes"], record["body_sha256"])
        if entries[record["id"]].read_bytes() != snapshots[record["id"]]:
            raise ValueError("Source changed during export: " + path)
    destination = output / f"{BASENAME}-{edition}.md"
    destination.write_bytes(assembled)
    return {"file": destination.name, "bytes": len(assembled), "sha256": sha(assembled),
            "documents": len(records), "outside_navigation": unlisted,
            "translation_fallbacks": fallback, "sources": records,
            "body_verification": "Every exported body matches its complete source body byte-for-byte."}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "output/markdown")
    args = parser.parse_args()
    output = args.output_dir.resolve()
    output.mkdir(parents=True, exist_ok=True)
    original = files(DOCS)
    order = sidebar_order(original)
    before_sidebar = SIDEBAR.read_bytes()
    editions = []
    if SITE == ROOT:
        editions.append(build("ru", original, order, output, []))
    else:
        editions.append(build("en", original, order, output, []))
        translated_root = SITE / "i18n/ru/docusaurus-plugin-content-docs/current"
        if translated_root.is_dir():
            translated = files(translated_root)
            fallback = sorted(set(original) - set(translated))
            editions.append(build("ru", {**original, **translated}, order, output, fallback))
    if SIDEBAR.read_bytes() != before_sidebar:
        raise ValueError("Sidebar changed during export")
    report = {"schema_version": 1, "generator": str(Path(__file__).relative_to(ROOT)),
              "generator_sha256": sha(Path(__file__).read_bytes()),
              "sidebar_sha256": sha(before_sidebar), "editions": editions}
    (output / "build-markdown-manifest.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for edition in editions:
        print(f"{output / edition['file']}: {edition['documents']} documents, {edition['bytes']:,} bytes")


if __name__ == "__main__":
    main()
