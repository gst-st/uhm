#!/usr/bin/env python3
"""Единый источник истины о системе маркеров статуса УГМ.

Зачем этот файл существует
--------------------------
Маркеры статуса (`[Т]`, `[С]`, `[Г]`, `[П]`, `[О]`, `[И]`, `[✗]`) — свободный
текст в трёхстах пятидесяти файлах корпуса. У них не было ни одного описания в
машиночитаемом виде, и это оказалось не мелочью, а **архитектурным
ограничением**:

1. Всякий потребитель вынужден угадывать набор символов. В
   `homoholograph/tools/status_consistency.py` класс был набран на глаз как
   `[TСCHПИO О]` — без кириллической `Т`, самого частого маркера корпуса
   (8919 вхождений). Исключение для расслоенных записей почти не срабатывало.
2. Два алфавита разошлись без надзора: 2973 кириллических маркера в английском
   корпусе, 280 латинских в русском, и **42 файла из 175** пишут одно понятие
   обоими способами — включая сам реестр статусов.
3. Синтаксис маркера совпадает с чужими нотациями: метки органов `[A]`…`[S]` в
   `prime-radiant.md`, аргументы операторов `\\mathbb{E}[V]` в формулах. Наивная
   правка их портит.

Отсюда конструкция: набор задан **кодовыми точками**, а не начертанием;
отображение локалей явное; всё, что маркером не является, перечислено. Все
инструменты обязаны читать отсюда, а не набирать классы символов заново.

Использование
-------------
    from status_markers import STATUSES, glyphs, is_marker_char
    python3 scripts/status_markers.py          # напечатать таблицу
"""
from __future__ import annotations

# Кодовые точки, а не буквы: 'Т' (U+0422) и 'T' (U+0054) неразличимы в
# начертании, и набранный глазом класс символов ошибётся молча.
STATUSES = [
    # ключ,     EN,        RU,        EN-название,             RU-название
    ("theorem",     "T", "Т", "Theorem",             "Теорема"),
    ("conditional", "C", "С", "Conditional theorem", "Условная теорема"),
    ("hypothesis",  "H", "Г", "Hypothesis",          "Гипотеза"),
    ("postulate",   "P", "П", "Postulate",           "Постулат"),
    ("definition",  "D", "О", "Definition",          "Определение"),
    ("interpretation", "I", "И", "Interpretation",   "Интерпретация"),
    ("retracted",   "✗", "✗", "Retracted",           "Ретрактировано"),
]

EN = {key: en for key, en, _, _, _ in STATUSES}
RU = {key: ru for key, _, ru, _, _ in STATUSES}
EN_TO_RU = {en: ru for _, en, ru, _, _ in STATUSES}
RU_TO_EN = {ru: en for _, en, ru, _, _ in STATUSES}

#: Глифы, законные в английском корпусе (`website/docs/`).
EN_GLYPHS = frozenset(EN.values())
#: Глифы, законные в русском корпусе (`website/i18n/ru/`).
RU_GLYPHS = frozenset(RU.values())

#: Одиночные буквы в скобках, которые маркерами НЕ являются. Перечислены явно,
#: потому что синтаксис у них тот же, и молчаливое совпадение испортило бы
#: чужую нотацию.
NOT_MARKERS = {
    # Метки органов прайм-радианта: таблица «орган → содержимое → проверка».
    "A": "орган прайм-радианта (арифметический этаж)",
    "B": "орган прайм-радианта (аналитический этаж)",
    "E": "орган прайм-радианта (навигатор)",
    "F": "орган прайм-радианта (калибровка)",
    "G": "орган прайм-радианта (пространство пар)",
    "J": "орган прайм-радианта (фазовый атлас)",
    "K": "орган прайм-радианта (оценщик)",
    "L": "орган прайм-радианта (пол БКМ)",
    "S": "орган прайм-радианта (доменный сенсор)",
    # Аргументы операторов внутри формул: \mathcal{D}^\dagger[Q], \mathbb{E}[V].
    "Q": "аргумент оператора в формуле",
    "V": "аргумент оператора в формуле",
}

#: Написания, которые встречаются в корпусе, но в легенде отсутствуют.
#: Чинятся не автоматически: у каждого своя история, решает человек.
SUSPECT = {
    "O": ("латинская O вместо [D]: «definition [O]» в axiom-omega", "D"),
    "Д": ("кириллическая Д вместо [О]: «Определение 1 [Д]»", "О"),
    "R": ("[R] в cosmological-constant — в легенде такого статуса нет", None),
}


def glyphs(locale: str) -> frozenset:
    """Законный набор глифов для локали: `en` или `ru`."""
    if locale not in ("en", "ru"):
        raise ValueError(f"локаль {locale!r} не en и не ru")
    return EN_GLYPHS if locale == "en" else RU_GLYPHS


def is_marker_char(ch: str) -> bool:
    """Является ли символ маркером статуса хоть в какой-то локали."""
    return ch in EN_GLYPHS or ch in RU_GLYPHS


def translate(ch: str, to_locale: str) -> str | None:
    """Перевести глиф маркера в другую локаль. `None` — если это не маркер."""
    if to_locale == "en":
        return ch if ch in EN_GLYPHS else RU_TO_EN.get(ch)
    if to_locale == "ru":
        return ch if ch in RU_GLYPHS else EN_TO_RU.get(ch)
    raise ValueError(f"локаль {to_locale!r} не en и не ru")


def main() -> int:
    print("Маркеры статуса УГМ — единый источник\n")
    print(f"{'ключ':<16} {'EN':<4} {'код':<8} {'RU':<4} {'код':<8} название")
    for key, en, ru, en_name, ru_name in STATUSES:
        print(f"{key:<16} [{en}]  U+{ord(en):04X}  [{ru}]  U+{ord(ru):04X}  "
              f"{en_name} / {ru_name}")
    print(f"\nНЕ маркеры ({len(NOT_MARKERS)}):")
    for ch, why in sorted(NOT_MARKERS.items()):
        print(f"   [{ch}] U+{ord(ch):04X} — {why}")
    print(f"\nПодозрительные написания ({len(SUSPECT)}):")
    for ch, (why, fix) in sorted(SUSPECT.items()):
        tail = f" → [{fix}]" if fix else " → решает человек"
        print(f"   [{ch}] U+{ord(ch):04X} — {why}{tail}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
