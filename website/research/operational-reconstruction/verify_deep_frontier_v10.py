    # Exact Fermi-Dirac vs Maxwell-Boltzmann equilibrium N_N abundance ratio n_N^FD(x)/n_N^MB(x)
    # (smooth u = t^2 16-pt half-Gauss-Hermite; exact massless asymptote n^FD(0)/n^MB(0) = 3/4 * zeta(3) = 0.90154268!):
