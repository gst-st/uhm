    def run_13ode(Y_in, M_in, mode_12="exact_lpm", custom_arr=None, use_fd_Neq=False, method="Radau", rtol=1e-7, atol=1e-13):
        H_y = Y_in.conj().T @ Y_in
        Gam = np.array([H_y[i, i].real * M_in[i] / (8.0 * np.pi) for i in range(3)])
        K_t = np.array([(H_y[i, i].real * v_EW**2 / M_in[i]) * 1e9 / 1.08e-3 for i in range(3)])
        eps_ten = np.zeros((3, 3, 3), dtype=complex); P_proj = np.zeros((3, 3, 3), dtype=complex)
        for i in range(3):
            Mi = M_in[i]; Hii = H_y[i, i].real
            P_proj[i] = np.outer(Y_in[:, i].conj(), Y_in[:, i]) / Hii
            for j in range(3):
                if j == i: continue
                xj = (M_in[j] / Mi)**2; reg = (1.0 - xj)**2 + (Gam[j] / Mi)**2 * xj
                g_V = np.sqrt(xj) * (1.0 - (1.0 + xj) * np.log((1.0 + xj) / xj))
                g_S = np.sqrt(xj) * (1.0 - xj) / reg; g_fl = (1.0 - xj) / reg
                M1 = np.outer(Y_in[:, i].conj(), Y_in[:, j])
                eps_ten[i] += ((M1*H_y[i,j] - M1.conj().T*H_y[j,i])*(g_V + g_S)
                             + (M1*H_y[j,i] - M1.conj().T*H_y[i,j])*g_fl) / (16.0j*np.pi*Hii)
        M_nu_eV = -(Y_in * v_EW) @ np.diag(1.0 / M_in) @ (Y_in * v_EW).T * 1e9
        W2_mat = (M_nu_eV.conj() @ M_nu_eV) * (M_in[0] / 1e10) * (0.186 / (0.1**2))
        r2 = M_in[1] / M_in[0]; r3 = M_in[2] / M_in[0]
        z_start = min(0.05, 0.05 / max(1.0, r3)); z_end = 40.0
        def unpack_N(v):
            M = np.zeros((3, 3), dtype=complex)
            M[0,0], M[1,1], M[2,2] = v[0], v[1], v[2]
            M[0,1] = v[3]+1j*v[4]; M[1,0] = np.conj(M[0,1])
            M[0,2] = v[5]+1j*v[6]; M[2,0] = np.conj(M[0,2])
            M[1,2] = v[7]+1j*v[8]; M[2,1] = np.conj(M[1,2])
            return M
        def pack_N(M):
            return np.array([M[0,0].real, M[1,1].real, M[2,2].real,
                             M[0,1].real, M[0,1].imag, M[0,2].real, M[0,2].imag, M[1,2].real, M[1,2].imag])
        arr_use = custom_arr if custom_arr is not None else f_lpm_vals
        arr_left = float(arr_use[0])
        rHs0, rHt0, rAs0, rAt10, rAt20 = float(r_Hs[0]), float(r_Ht[0]), float(r_As[0]), float(r_At1[0]), float(r_At2[0])
        def rhs(u, y):
            z = np.exp(u); N_vec = y[:3]; Nmat = unpack_N(y[3:12]); Dc = y[12]
            dN_RH = np.zeros(3); dNmat = np.zeros((3, 3), dtype=complex)
            diag_N = np.array([Nmat[0,0].real, Nmat[1,1].real, Nmat[2,2].real])
            N_eff = -Nmat.copy()
            de = C_noyc @ diag_N + v_c * Dc
            dDc_dz = -C_c_q * (float(np.dot(w_c, diag_N)) + lam_c * Dc)
            N_eff[0,0], N_eff[1,1], N_eff[2,2] = de[0], de[1], de[2]
            for i, ri in enumerate([1.0, r2, r3]):
                xx = ri * z
                if xx > 80.0: continue
                k1, k2 = kn(1, xx), kn(2, xx); Neq_mb = 0.5*xx*xx*k2
                lx = np.log(max(xx, 1e-3))
                if use_fd_Neq:
                    # Exact self-consistent BDP-normalized FD equilibrium (n_ref = n_N^FD(0) = n_l^FD = 3*zeta(3)/(2pi^2) T^3):
                    # Neq_FD(x) = c_fd_bdp * (0.5 x^2 K_2(x)) * (n_N^FD/n_N^MB) -> 1.0 as x -> 0,
                    # W_FD = c_fd_bdp * (0.25 K r^4 z^3 K_1(x)) = 0.5 * D_FD * Neq_FD (exact detailed balance!).
                    nrat = float(np.interp(lx, lxs_neq, neq_rat, left=0.75 * zeta3, right=1.0))
                    Neq = c_fd_bdp * Neq_mb * nrat
                    D = K_t[i]*(ri**2)*z*(k1/max(1e-300, k2)) / nrat
                    W = c_fd_bdp * 0.25*K_t[i]*(ri**4)*(z**3)*k1
                else:
                    Neq = Neq_mb
                    D = K_t[i]*(ri**2)*z*(k1/max(1e-300, k2))
                    W = 0.25*K_t[i]*(ri**4)*(z**3)*k1
                rHs  = float(np.interp(lx, lxs_g, r_Hs,  left=rHs0,  right=0.0))
                rHt  = float(np.interp(lx, lxs_g, r_Ht,  left=rHt0,  right=0.0))
                rAs  = float(np.interp(lx, lxs_g, r_As,  left=rAs0,  right=0.0))
                rAt1 = float(np.interp(lx, lxs_g, r_At1, left=rAt10, right=0.0))
                rAt2 = float(np.interp(lx, lxs_g, r_At2, left=rAt20, right=0.0))
                ratN = N_vec[i]/Neq if Neq > 1e-30 else 1.0
                f12 = float(np.interp(np.log(max(xx, 0.05)), lxs_lpm, arr_use, left=arr_left, right=1.0)) if mode_12 == "exact_lpm" else 1.0
                Dt = D * (f12 + rHs + 2.0*rHt + rAs + rAt1 + rAt2)
                Wt = W * (f12 + ratN*(rHs + rAs) + 2.0*rHt + rAt1 + rAt2)
                dN_RH[i] = -Dt*(N_vec[i] - Neq)
                dNmat += -eps_ten[i]*Dt*(N_vec[i] - Neq) + 0.5*Wt*(P_proj[i]@N_eff + N_eff@P_proj[i])
            dNmat += 0.5*(W2_mat@N_eff + N_eff@W2_mat)/(z*z)
            dNmat[0,2] -= C_tau*Nmat[0,2]; dNmat[2,0] -= C_tau*Nmat[2,0]
            dNmat[1,2] -= C_tau*Nmat[1,2]; dNmat[2,1] -= C_tau*Nmat[2,1]
            dNmat[0,1] -= C_mu*Nmat[0,1];  dNmat[1,0] -= C_mu*Nmat[1,0]
            return np.concatenate((z*dN_RH, z*pack_N(dNmat), [z*dDc_dz]))
        y0 = np.zeros(13)
        for i, ri in enumerate([1.0, r2, r3]):
            xx0 = ri * z_start
            Neq_mb0 = 0.5*(xx0**2)*kn(2, xx0)
            if use_fd_Neq:
                nrat0 = float(np.interp(np.log(max(xx0, 1e-3)), lxs_neq, neq_rat, left=0.75 * zeta3, right=1.0))
                y0[i] = c_fd_bdp * Neq_mb0 * nrat0
            else:
                y0[i] = Neq_mb0
        sol = solve_ivp(rhs, [np.log(z_start), np.log(z_end)], y0, method=method, rtol=rtol, atol=atol)
        Nf = unpack_N(sol.y[3:12, -1])
        return 0.96e-2 * float(np.trace(Nf).real)

