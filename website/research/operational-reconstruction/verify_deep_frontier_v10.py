    xs_g = np.geomspace(1e-3, 80.0, 100); tg_g = np.geomspace(1e-4, 35.0, 150)
    r_Hs, r_Ht, r_As, r_At1, r_At2 = [np.zeros_like(xs_g) for _ in range(5)]
    def int_ch(x, u_min, fn):
        k1x = kn(1, x)
        if k1x < 1e-250: return 0.0
        u = u_min + (tg_g / x)**2; du_dt = 2.0 * tg_g / (x**2)
        wt = np.sqrt(u) * kn(1, x * np.sqrt(u)) * du_dt
        return float(np.trapezoid(wt * fn(u), tg_g) / (8.0 * np.pi * k1x))
    for ix, x in enumerate(xs_g):
        ah = (mh_T / x)**2; al = (ml_T / x)**2
        r_Hs[ix] = int_ch(x, 1.0, lambda u: (3.0*y_t**2/(2.0*np.pi))*((u-1.0)/u)**2)
        r_Ht[ix] = int_ch(x, 1.0, lambda u: (3.0*y_t**2/(2.0*np.pi))*np.maximum((u-1.0)+(1.0-2.0*ah)*np.log((u-1.0+ah)/ah)+(ah-1.0)*(u-1.0)/(u-1.0+ah), 0.0)/u)
        for w_g, mA_T in [(3.0*g2_sq, mW_T), (gY_sq, mB_T)]:
            u_As  = max((1.0 + ml_T/x)**2, ((mh_T + mA_T)/x)**2)
            u_At1 = max((1.0 + mh_T/x)**2, ((ml_T + mA_T)/x)**2)
            u_At2 = max((1.0 + mA_T/x)**2, ((ml_T + mh_T)/x)**2)
            r_As[ix]  += int_ch(x, u_As,  lambda u: (w_g/(4.0*np.pi))*np.maximum(((u**2-2*u+2)/u**2)*np.log((u-1.0+al)/al) - (u-1.0)*(u-2.0)/u**2, 0.0))
            r_At1[ix] += int_ch(x, u_At1, lambda u: (w_g/(4.0*np.pi))*np.maximum((2.0*(u-1.0)/u**2)*np.log((u-1.0+ah)/ah) + (u-1.0)*(u-3.0)/(2.0*u**2), 0.0))
            r_At2[ix] += int_ch(x, u_At2, lambda u: (w_g/(4.0*np.pi))*np.maximum(((u-1.0)*np.log((u-1.0+al)/al) + (2.0*u/(u-1.0+ah+al))*(np.log((u-1.0+ah)/ah)+np.log((u-1.0+al)/al)))/u, 0.0))
    lxs_g = np.log(xs_g)
    lxs_lpm = np.log(xs_lpm)
