def lie_closure_dim(gens, tol=1e-10, max_iter=10):
    """Compute exact real dimension of Lie algebra generated by real/complex matrices."""
    def to_real_vec(M):
        return np.concatenate([M.real.ravel(), M.imag.ravel()])

    basis_mats = []
    basis_vecs = []

    def try_add(M):
        v = to_real_vec(M)
        if np.linalg.norm(v) < tol:
            return False
        if not basis_vecs:
            basis_mats.append(M / np.linalg.norm(v))
            basis_vecs.append(v / np.linalg.norm(v))
            return True
        B = np.column_stack(basis_vecs)
        proj = B @ (B.T @ v)
        rem = v - proj
        nr = np.linalg.norm(rem)
        if nr > tol:
            # Re-orthogonalize (Modified Gram-Schmidt)
            rem = rem / nr
            rem = rem - B @ (B.T @ rem)
            nr2 = np.linalg.norm(rem)
            if nr2 > tol:
                n = M.shape[0]
                rem_u = rem / nr2
                M_u = rem_u[:n*n].reshape(n, n) + 1j * rem_u[n*n:].reshape(n, n)
                basis_mats.append(M_u)
                basis_vecs.append(rem_u)
                return True
        return False

    for G in gens:
        try_add(G)

    for _ in range(max_iter):
        added = False
        cur = list(basis_mats)
        for i in range(len(cur)):
            for j in range(i + 1, len(cur)):
                C = cur[i] @ cur[j] - cur[j] @ cur[i]
                if try_add(C):
                    added = True
        if not added:
            break
    return len(basis_mats)


